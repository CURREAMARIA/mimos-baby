-- 1) Administradoras (solo estos correos pueden editar)
create table if not exists admins (email text primary key);
insert into admins (email) values ('curreamaria@gmail.com') on conflict do nothing;

create or replace function es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from admins where email = (auth.jwt() ->> 'email'));
$$;

-- 2) Categorías (los botoncitos de filtro)
create table if not exists categorias (
  id text primary key,
  nombre text not null,
  orden int default 0
);

-- 3) Productos
create table if not exists productos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  marca text default 'Carter''s',
  precio int not null,
  precios_talla jsonb default '{}'::jsonb,
  tallas text[] default '{RN,3M,6M,9M,12M,18M,24M}',
  genero text default 'nina' check (genero in ('nina','nino','unisex')),
  categoria text references categorias(id) on update cascade,
  etiqueta text,
  imagen text,
  imagenes text[] default '{}',
  activo boolean default true,
  orden int default 0,
  creado timestamptz default now()
);

-- 4) Costos (privado: solo tú los ves, las clientas no)
-- Si ya habías creado la tabla antes, esto agrega la columna de fotos extra:
alter table productos add column if not exists imagenes text[] default '{}';

create table if not exists costos (
  producto_id bigint primary key references productos(id) on delete cascade,
  costo int
);

-- 5) Permisos
alter table admins enable row level security;
alter table categorias enable row level security;
alter table productos enable row level security;
alter table costos enable row level security;

drop policy if exists "cat_leer" on categorias;
create policy "cat_leer" on categorias for select using (true);
drop policy if exists "cat_admin" on categorias;
create policy "cat_admin" on categorias for all using (es_admin()) with check (es_admin());

drop policy if exists "prod_leer" on productos;
create policy "prod_leer" on productos for select using (activo or es_admin());
drop policy if exists "prod_admin" on productos;
create policy "prod_admin" on productos for all using (es_admin()) with check (es_admin());

drop policy if exists "costo_admin" on costos;
create policy "costo_admin" on costos for all using (es_admin()) with check (es_admin());

drop policy if exists "admins_leer" on admins;
create policy "admins_leer" on admins for select using (es_admin());

-- 6) Carpeta de fotos
insert into storage.buckets (id, name, public) values ('productos', 'productos', true)
on conflict (id) do nothing;

drop policy if exists "fotos_leer" on storage.objects;
create policy "fotos_leer" on storage.objects for select using (bucket_id = 'productos');
drop policy if exists "fotos_subir" on storage.objects;
create policy "fotos_subir" on storage.objects for insert with check (bucket_id = 'productos' and es_admin());
drop policy if exists "fotos_editar" on storage.objects;
create policy "fotos_editar" on storage.objects for update using (bucket_id = 'productos' and es_admin());
drop policy if exists "fotos_borrar" on storage.objects;
create policy "fotos_borrar" on storage.objects for delete using (bucket_id = 'productos' and es_admin());


