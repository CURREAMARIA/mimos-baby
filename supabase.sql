-- Las clientas solo pueden preguntar si un código sirve, no ver la lista
create or replace function validar_codigo(c text) returns int
language sql stable security definer set search_path = public as $$
  select coalesce((select pct from codigos where upper(codigo) = upper(trim(c)) and activo), 0);
$$;
grant execute on function validar_codigo(text) to anon, authenticated;

